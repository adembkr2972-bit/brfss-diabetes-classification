import os
import sys
from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    f1_score,
    log_loss,
    precision_recall_fscore_support,
    recall_score,
    roc_auc_score,
    roc_curve,
)

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from scripts.config import config


def setup_logger() -> logging.Logger:
    logger = logging.getLogger("9_evaluate_models")
    logger.setLevel(logging.INFO)
    logger.handlers.clear()

    formatter = logging.Formatter("[%(asctime)s] %(levelname)s - %(message)s")
    file_handler = logging.FileHandler(config.LOGS_DIR / "9_evaluate_models.log", mode="w", encoding="utf-8")
    file_handler.setFormatter(formatter)
    stream_handler = logging.StreamHandler(sys.stdout)
    stream_handler.setFormatter(formatter)
    logger.addHandler(file_handler)
    logger.addHandler(stream_handler)
    return logger


def positive_scores(model, features: pd.DataFrame) -> np.ndarray | None:
    if hasattr(model, "predict_proba"):
        return model.predict_proba(features)[:, 1]
    if hasattr(model, "decision_function"):
        return np.asarray(model.decision_function(features), dtype=float)
    return None


def metrics_dict(model_name: str, y_true: pd.Series, y_pred: np.ndarray, y_score: np.ndarray | None, has_probability: bool = False) -> dict[str, float]:
    precision_macro, recall_macro, f1_macro, _ = precision_recall_fscore_support(
        y_true, y_pred, average="macro", zero_division=0
    )
    precision_weighted, recall_weighted, f1_weighted, _ = precision_recall_fscore_support(
        y_true, y_pred, average="weighted", zero_division=0
    )
    class_precision, class_recall, class_f1, class_support = precision_recall_fscore_support(
        y_true, y_pred, labels=[0, 1], average=None, zero_division=0
    )
    row = {
        "model_name": model_name,
        "display_label": config.display_model_label(model_name),
        "accuracy": accuracy_score(y_true, y_pred),
        "precision_macro": precision_macro,
        "precision_weighted": precision_weighted,
        "recall_macro": recall_macro,
        "recall_weighted": recall_weighted,
        "f1_macro": f1_macro,
        "f1_weighted": f1_weighted,
        "precision_class_0": class_precision[0],
        "recall_class_0": class_recall[0],
        "f1_class_0": class_f1[0],
        "support_class_0": class_support[0],
        "precision_class_1": class_precision[1],
        "recall_class_1": class_recall[1],
        "f1_class_1": class_f1[1],
        "support_class_1": class_support[1],
        "roc_auc": np.nan,
        "log_loss": np.nan,
    }
    if y_score is not None:
        row["roc_auc"] = roc_auc_score(y_true, y_score)
        if has_probability:
            row["log_loss"] = log_loss(y_true, np.clip(y_score, 1e-9, 1 - 1e-9), labels=[0, 1])
    return row


def plot_confusion(y_true: pd.Series, y_pred: np.ndarray, output_path: Path) -> None:
    matrix = confusion_matrix(y_true, y_pred, labels=[0, 1])
    plt.figure(figsize=(6, 5))
    sns.heatmap(
        matrix,
        annot=True,
        fmt="d",
        cmap="Blues",
        xticklabels=["Non-Diabetic (0)", "Diabetic (1)"],
        yticklabels=["Non-Diabetic (0)", "Diabetic (1)"],
    )
    plt.xlabel("Predicted")
    plt.ylabel("True")
    plt.tight_layout()
    plt.savefig(output_path, dpi=150)
    plt.close()


def main() -> None:
    for path in [config.LOGS_DIR, config.FIGURES_DIR, config.METRICS_DIR]:
        os.makedirs(path, exist_ok=True)

    logger = setup_logger()
    logger.info("Starting validation evaluation.")
    run_started = float(config.RERUN_STARTED_PATH.read_text(encoding="utf-8").strip())

    X_train = pd.read_parquet(config.X_TRAIN_PATH)
    y_train = pd.read_parquet(config.Y_TRAIN_PATH)[config.TARGET_BINARY_COL]
    X_val = pd.read_parquet(config.X_VAL_PATH)
    y_val = pd.read_parquet(config.Y_VAL_PATH)[config.TARGET_BINARY_COL]

    validation_rows = []
    overfit_rows = []
    roc_payload = []

    for model_name in config.MODEL_NAMES:
        logger.info("Evaluating model: %s", model_name)
        model_path = config.MODELS_DIR / f"tuned_{model_name}.joblib"
        if not model_path.exists() or model_path.stat().st_mtime <= run_started:
            model_path = config.MODELS_DIR / f"baseline_{model_name}.joblib"
        if not model_path.exists() or model_path.stat().st_mtime <= run_started:
            validation_rows.append({"model_name": model_name})
            overfit_rows.append({"model_name": model_name})
            continue

        try:
            model = joblib.load(model_path)
            val_pred = model.predict(X_val)
            val_score = positive_scores(model, X_val)

            has_probability = hasattr(model, "predict_proba")
            val_metrics = metrics_dict(model_name, y_val, val_pred, val_score, has_probability)
            validation_rows.append(val_metrics)
            if model_name == "SVM":
                # SVM training/tuning uses a stratified subset, and evaluating
                # it across all training rows is prohibitively expensive and
                # would not be an in-sample training score for that model.
                overfit_rows.append(
                    {
                        "model_name": model_name,
                        "train_f1_macro": np.nan,
                        "val_f1_macro": val_metrics["f1_macro"],
                        "overfit_gap": np.nan,
                        "overfit_flag": np.nan,
                    }
                )
            else:
                train_pred = model.predict(X_train)
                train_score = positive_scores(model, X_train)
                train_metrics = metrics_dict(model_name, y_train, train_pred, train_score, has_probability)
                overfit_gap = train_metrics["f1_macro"] - val_metrics["f1_macro"]
                overfit_rows.append(
                    {
                        "model_name": model_name,
                        "train_f1_macro": train_metrics["f1_macro"],
                        "val_f1_macro": val_metrics["f1_macro"],
                        "overfit_gap": overfit_gap,
                        "overfit_flag": overfit_gap > 0.10,
                    }
                )

            plot_confusion(y_val, val_pred, config.FIGURES_DIR / f"confusion_matrix_{model_name}.png")
            if val_score is not None:
                fpr, tpr, _ = roc_curve(y_val, val_score)
                roc_payload.append((model_name, fpr, tpr, val_metrics["roc_auc"]))
        except Exception:
            logger.exception("Validation evaluation failed for %s", model_name)
            validation_rows.append({"model_name": model_name})
            overfit_rows.append({"model_name": model_name})

    # Majority-class baseline: predicts the most common training class.
    majority_class = int(y_train.value_counts().idxmax())
    baseline_train_pred = np.full(len(y_train), majority_class, dtype=int)
    baseline_val_pred = np.full(len(y_val), majority_class, dtype=int)
    validation_rows.append(metrics_dict("MajorityBaseline", y_val, baseline_val_pred, None))
    baseline_train_metrics = metrics_dict("MajorityBaseline", y_train, baseline_train_pred, None)
    baseline_val_metrics = metrics_dict("MajorityBaseline", y_val, baseline_val_pred, None)
    overfit_rows.append(
        {
            "model_name": "MajorityBaseline",
            "train_f1_macro": baseline_train_metrics["f1_macro"],
            "val_f1_macro": baseline_val_metrics["f1_macro"],
            "overfit_gap": baseline_train_metrics["f1_macro"] - baseline_val_metrics["f1_macro"],
            "overfit_flag": False,
        }
    )

    validation_df = pd.DataFrame(validation_rows)
    overfit_df = pd.DataFrame(overfit_rows)
    validation_df["display_label"] = validation_df["model_name"].map(config.display_model_label)
    overfit_df["display_label"] = overfit_df["model_name"].map(config.display_model_label)
    validation_df.to_csv(config.FULL_VALIDATION_METRICS_PATH, index=False)
    overfit_df.to_csv(config.OVERFITTING_ANALYSIS_PATH, index=False)

    if roc_payload:
        plt.figure(figsize=(8, 6))
        for model_name, fpr, tpr, auc_value in roc_payload:
            plt.plot(fpr, tpr, label=f"{config.display_model_label(model_name)} (AUC={auc_value:.3f})")
        plt.plot([0, 1], [0, 1], linestyle="--", color="grey")
        plt.xlabel("False Positive Rate")
        plt.ylabel("True Positive Rate")
        plt.title("Validation ROC Curves")
        plt.legend()
        plt.tight_layout()
        plt.savefig(config.FIGURES_DIR / "roc_curve_all_models.png", dpi=150)
        plt.close()

    if not validation_df.empty and not overfit_df.empty:
        plot_df = validation_df.merge(overfit_df, on="model_name", how="left").sort_values("f1_macro", ascending=True)
        plot_df["display_label"] = plot_df["model_name"].map(config.display_model_label)
        colors = []
        for gap in plot_df["overfit_gap"].fillna(0):
            if gap < 0.05:
                colors.append("green")
            elif gap <= 0.10:
                colors.append("orange")
            else:
                colors.append("red")
        plt.figure(figsize=(9, 6))
        plt.barh(plot_df["display_label"], plot_df["f1_macro"], color=colors)
        plt.xlabel("Validation F1 (macro)")
        plt.title("Validation F1 Comparison")
        plt.tight_layout()
        plt.savefig(config.FIGURES_DIR / "f1_comparison_bar.png", dpi=150)
        plt.close()

    logger.info("Saved validation evaluation outputs.")


if __name__ == "__main__":
    main()
